#!/usr/bin/env python3
"""Compare the tau-based theory matrix with final experimental matrices."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

from _tau_metric_common import (
    ComparisonStats,
    compare_matrices,
    default_final_data_dir,
    default_output_dir,
    default_theory_csv,
    format_float,
    normalize_columns,
    read_matrix_sheet,
    read_theory_matrix_csv,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compare the theory matrix with final experimental matrices.")
    parser.add_argument(
        "--theory-csv",
        type=Path,
        default=default_theory_csv(),
        help="Theory matrix CSV generated by 01_tau_kernel_to_probability_matrix.py.",
    )
    parser.add_argument(
        "--final-data-dir",
        type=Path,
        default=default_final_data_dir(),
        help="Directory containing triplicate_full9_aggregate.xlsx and run folders 1/2/3.",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory for generated outputs. Defaults to the script directory.",
    )
    return parser.parse_args()


def write_per_cell_csv(path: Path, dataset_name: str, theory, experiment) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["dataset", "detector_l", "lock_l", "theory_pct", "experiment_pct", "abs_error_pp"])
        for row_idx, det_l in enumerate(theory.row_labels):
            for col_idx, lock_l in enumerate(theory.col_labels):
                theory_pct = 100.0 * theory.values[row_idx][col_idx]
                exp_pct = 100.0 * experiment.values[row_idx][col_idx]
                writer.writerow(
                    [
                        dataset_name,
                        det_l,
                        lock_l,
                        f"{theory_pct:.6f}",
                        f"{exp_pct:.6f}",
                        f"{abs(theory_pct - exp_pct):.6f}",
                    ]
                )


def append_per_cell_rows(handle, dataset_name: str, theory, experiment) -> None:
    writer = csv.writer(handle)
    for row_idx, det_l in enumerate(theory.row_labels):
        for col_idx, lock_l in enumerate(theory.col_labels):
            theory_pct = 100.0 * theory.values[row_idx][col_idx]
            exp_pct = 100.0 * experiment.values[row_idx][col_idx]
            writer.writerow(
                [
                    dataset_name,
                    det_l,
                    lock_l,
                    f"{theory_pct:.6f}",
                    f"{exp_pct:.6f}",
                    f"{abs(theory_pct - exp_pct):.6f}",
                ]
            )


def write_summary_block(handle, name: str, stats: ComparisonStats) -> None:
    handle.write(f"[{name}]\n")
    handle.write(f"matrix_MAE_pp = {stats.matrix_mae_pp:.6f}\n")
    handle.write(f"diag_MAE_pp = {stats.diag_mae_pp:.6f}\n")
    handle.write(f"offdiag_MAE_pp = {stats.offdiag_mae_pp:.6f}\n")
    handle.write(f"top1_match = {stats.top1_match}/{stats.columns}\n")
    handle.write(f"top2_match = {stats.top2_match}/{stats.columns}\n")
    handle.write("\n")


def main() -> None:
    args = parse_args()
    out_dir = default_output_dir(args.output_dir)
    theory = read_theory_matrix_csv(args.theory_csv)

    aggregate_xlsx = args.final_data_dir / "triplicate_full9_aggregate.xlsx"
    aggregate_matrix = read_matrix_sheet(aggregate_xlsx, "combined_percentage")
    aggregate_matrix_norm = normalize_columns(aggregate_matrix, scale=1.0)
    aggregate_stats = compare_matrices(theory, aggregate_matrix_norm)

    aggregate_csv = out_dir / "aggregate_matrix_comparison.csv"
    write_per_cell_csv(aggregate_csv, "aggregate", theory, aggregate_matrix_norm)

    per_run_csv = out_dir / "per_run_matrix_comparison.csv"
    with per_run_csv.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["dataset", "detector_l", "lock_l", "theory_pct", "experiment_pct", "abs_error_pp"])
        per_run_stats: list[tuple[str, ComparisonStats]] = []
        for run_name in ["1", "2", "3"]:
            run_xlsx = args.final_data_dir / run_name / "full9_matrix_with_uncertainty.xlsx"
            run_matrix = normalize_columns(read_matrix_sheet(run_xlsx, "mean"), scale=1.0)
            append_per_cell_rows(handle, f"run_{run_name}", theory, run_matrix)
            per_run_stats.append((f"run_{run_name}", compare_matrices(theory, run_matrix)))

    summary_path = out_dir / "comparison_summary.txt"
    with summary_path.open("w", encoding="utf-8") as handle:
        handle.write("Theory vs experiment matrix comparison summary\n\n")
        handle.write(f"theory_csv = {args.theory_csv}\n")
        handle.write(f"aggregate_xlsx = {aggregate_xlsx}\n")
        handle.write(f"aggregate_sheet = combined_percentage\n\n")
        write_summary_block(handle, "aggregate", aggregate_stats)
        for run_name, stats in per_run_stats:
            write_summary_block(handle, run_name, stats)

        handle.write("Aggregate diagonal comparison (theory_pct vs experiment_pct):\n")
        for idx, label in enumerate(theory.col_labels):
            handle.write(
                "  "
                f"l={label}: {100.0 * theory.values[idx][idx]:.6f}% vs "
                f"{100.0 * aggregate_matrix_norm.values[idx][idx]:.6f}%\n"
            )

    print(f"Wrote {aggregate_csv}")
    print(f"Wrote {per_run_csv}")
    print(f"Wrote {summary_path}")
    print(
        "Aggregate summary: "
        f"matrix_MAE_pp={aggregate_stats.matrix_mae_pp:.3f}, "
        f"diag_MAE_pp={aggregate_stats.diag_mae_pp:.3f}, "
        f"offdiag_MAE_pp={aggregate_stats.offdiag_mae_pp:.3f}, "
        f"top1={aggregate_stats.top1_match}/{aggregate_stats.columns}, "
        f"top2={aggregate_stats.top2_match}/{aggregate_stats.columns}"
    )


if __name__ == "__main__":
    main()
